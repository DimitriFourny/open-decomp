/** Curated symbolic constants of library call arguments (`open(path, O_WRONLY | O_CREAT)`).
 * Headers mostly `#define` these, so no declaration ties a parameter to its constants: this
 * table does, per function and argument index. The values are not stated here; they are
 * read per target ABI from the real headers by `scripts/generate-library-types.ts` (they
 * differ between Linux, Darwin and Windows) and a name a platform lacks is not printed
 * there. Presentation only: a constant spelled from this table is the same number. */
export interface ConstantSet {
  /** `values`: exactly one name; `flags`: an OR of names (bits not covered stay a number);
   * `octal`: no names, the number is printed in octal (file permission modes). */
  readonly kind: 'values' | 'flags' | 'octal';
  /** Preferred spelling first where two names share a value (`MAP_ANONYMOUS`, `MAP_ANON`). */
  readonly names: readonly string[];
  /** `flags` only: value fields inside the flag word, e.g. `open`'s access mode
   * (`O_RDONLY` is 0 under `O_ACCMODE`). A mask is a header name or a hex literal; where
   * the platform lacks the mask, the field's names are plain flags. */
  readonly fields?: readonly { readonly mask: string; readonly names: readonly string[] }[];
}

const values = (...names: string[]): ConstantSet => ({ kind: 'values', names });
const flags = (names: readonly string[], fields?: ConstantSet['fields']): ConstantSet => ({
  kind: 'flags',
  names,
  ...(fields ? { fields } : {}),
});

